import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { build } from 'vite'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const destination = join(root, 'internal/structure/parser.bundle.js')

export async function buildStructureParser({ check = false } = {}) {
  const source = await readFile(join(root, 'src/structure-parser-entry.ts'))
  const sourceSHA = createHash('sha256').update(source).digest('hex')
  const hash = createHash('sha256')
  for (const path of ['parse.go', 'go.go', 'javascript.go', 'types.go']) {
    hash.update(path).update('\0').update(await readFile(join(root, 'internal/structure', path)))
  }
  const nativeSHA = hash.digest('hex')
  const versions = {}
  for (const name of ['@lezer/javascript', '@lezer/lr', '@lezer/common', '@lezer/highlight']) {
    versions[name] = JSON.parse(await readFile(join(root, 'node_modules', name, 'package.json'), 'utf8')).version
  }
  const goMod = await readFile(join(root, 'go.mod'), 'utf8')
  const gojaVersion = goMod.match(/github\.com\/dop251\/goja\s+(\S+)/)?.[1]
  if (!gojaVersion) throw new Error('Missing pinned Goja runtime')
  const result = await build({
    root, configFile: false, logLevel: 'warn', resolve: { preserveSymlinks: true },
    build: {
      write: false, minify: false, sourcemap: false, target: 'es2022',
      lib: { entry: join(root, 'src/structure-parser-entry.ts'), name: 'LogicMarginStructure', formats: ['iife'] },
      rolldownOptions: { output: { comments: false } },
    },
  })
  const chunks = (Array.isArray(result) ? result : [result]).flatMap(output => output.output)
  if (chunks.length !== 1 || chunks[0].type !== 'chunk' || chunks[0].imports.length || chunks[0].dynamicImports.length) {
    throw new Error('Structure parser must be a single self-contained JS bundle')
  }
  const bundle = `// Generated by scripts/build-structure-parser.mjs; do not edit.\n// Sources SHA256: ${sourceSHA}\n// Native SHA256: ${nativeSHA}\n// Grammar versions: ${JSON.stringify(versions)}\n// Goja runtime: ${gojaVersion}\n${chunks[0].code}`
  if (check) {
    if (await readFile(destination, 'utf8') !== bundle) throw new Error('parser.bundle.js is stale; rebuild it')
  } else {
    await mkdir(dirname(destination), { recursive: true })
    await writeFile(destination, bundle)
  }
  return { sourceSHA, nativeSHA, versions, gojaVersion, bundleSHA: createHash('sha256').update(bundle).digest('hex'), bytes: Buffer.byteLength(bundle) }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  console.log(JSON.stringify(await buildStructureParser({ check: process.argv.includes('--check') })))
}
