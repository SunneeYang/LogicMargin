import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { build } from 'vite'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sources = ['src/graph-precompute-entry.ts', 'src/graph-layout.ts', 'src/graph-routing.ts', 'src/graph-focus.ts', 'src/graph-label.ts', 'src/graph-order.ts']
const destination = join(root, 'internal/precompute/graph.bundle.js')

export async function buildGraphPrecompute({ check = false } = {}) {
  const hash = createHash('sha256')
  for (const path of sources) hash.update(path).update('\0').update(await readFile(join(root, path))).update('\0')
  const sourceSHA = hash.digest('hex')
  const goMod = await readFile(join(root, 'go.mod'), 'utf8')
  const gojaVersion = goMod.match(/github\.com\/dop251\/goja\s+(\S+)/)?.[1]
  if (!gojaVersion) throw new Error('Missing pinned Goja runtime')
  const nativeSHA = createHash('sha256').update(await readFile(join(root, 'internal/precompute/native_layout.go'))).digest('hex')
  const result = await build({
    root, configFile: false, logLevel: 'warn', resolve: { preserveSymlinks: true },
    build: {
      write: false, minify: false, sourcemap: false, target: 'es2022',
      lib: { entry: join(root, sources[0]), name: 'LogicMarginLayout', formats: ['iife'] },
      rolldownOptions: { output: { comments: false } },
    },
  })
  const chunks = (Array.isArray(result) ? result : [result]).flatMap(output => output.output)
  if (chunks.length !== 1 || chunks[0].type !== 'chunk') throw new Error('Layout must be a single self-contained JS bundle')
  const bundle = `// Generated by scripts/build-graph-precompute.mjs; do not edit.\n// Sources SHA256: ${sourceSHA}\n// Native SHA256: ${nativeSHA}\n// Goja runtime: ${gojaVersion}\n${chunks[0].code}`
  if (check) {
    if (await readFile(destination, 'utf8') !== bundle) throw new Error('graph.bundle.js is stale; rebuild it')
  } else {
    await mkdir(dirname(destination), { recursive: true })
    await writeFile(destination, bundle)
  }
  return { sourceSHA, bundleSHA: createHash('sha256').update(bundle).digest('hex'), bytes: Buffer.byteLength(bundle) }
}

async function writeOracle() {
  const { layoutCases } = await import('../internal/precompute/testdata/layout-cases.mjs')
  const { layoutGraph } = await import('../src/graph-layout.ts')
  const { comparisonLayout } = await import('../src/graph-focus.ts')
  const { compareGraphIds } = await import('../src/graph-order.ts')
  const cases = []
  for (const { name, input, authored, expectedFailure = false } of layoutCases()) {
    const sizes = new Map((input.sizes ?? []).map(({ id, width, height }) => [id, { width, height }]))
    try {
      const result = input.reference
        ? comparisonLayout(input.nodes, input.edges, input.reference.nodes, input.reference.edges, sizes)
        : layoutGraph(input.nodes, input.edges, sizes)
      cases.push({ name, input, expected: { nodes: Object.fromEntries(result.nodes), edges: Object.fromEntries(result.edges), usesAuthoredPositions: authored } })
    } catch (error) {
      if (!expectedFailure) throw new Error(`V8 oracle failed for ${name}`, { cause: error })
      cases.push({ name, input, expectedError: String(error) })
    }
  }
  const ids = ['a', 'A', 'á', 'ä', 'é', 'e\u0301', 'Z', 'z', '中', '文', '😀', '🚀', '_', '-', '.', ':', '[', ']', '"', '1', '10', '2', 'ß', 'ss', 'å', 'œ', 'ø', 'Å', '💩', '🫠']
  const oracle = { node: process.versions.node, icu: process.versions.icu, locale: Intl.Collator().resolvedOptions().locale,
    sources: (await buildGraphPrecompute({ check: true })).sourceSHA,
    collation: ids.flatMap(a => ids.map(b => ({ a, b, sign: compareGraphIds(a, b) }))), cases }
  await writeFile(join(root, 'internal/precompute/testdata/layout-oracle.json'), `${JSON.stringify(oracle)}\n`)
  return { cases: cases.length, collationPairs: oracle.collation.length }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  console.log(JSON.stringify(await buildGraphPrecompute({ check: process.argv.includes('--check') })))
  if (process.argv.includes('--write-oracle')) console.log(JSON.stringify(await writeOracle()))
}
