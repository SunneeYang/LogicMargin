test('canvas, review-panel and task shortcuts reuse the existing controls without acting behind a modal', async ({ page }) => {
  await openFixture(page)
  const scale = () => page.locator('.react-flow__viewport').evaluate(element => Number(/scale\(([^)]+)\)/.exec((element as HTMLElement).style.transform)![1]))
  const original = await scale()
  await page.keyboard.press('Shift+=')
  await expect.poll(scale).toBeGreaterThan(original)
  await page.keyboard.press('-')
  await expect.poll(scale).toBeCloseTo(original, 3)
  await page.keyboard.press('Shift+1')
  await expect(page.locator('.canvas')).toHaveAttribute('data-viewport-ready', 'true')
  await page.keyboard.press('Shift+2')
  await expect(page.locator('.canvas')).toHaveAttribute('data-viewport-ready', 'true')
  await page.keyboard.press('f')
  await expect(page.locator('.app-shell')).toHaveClass(/is-focused/)
  await page.keyboard.press('f')
  await expect(page.locator('.app-shell')).not.toHaveClass(/is-focused/)
  await page.keyboard.press('Shift+B')
  await expect(page.locator('.inspector')).toHaveClass(/is-open/)
  await page.keyboard.press('Shift+B')
  await expect(page.locator('.inspector')).not.toHaveClass(/is-open/)
  await page.locator('.react-flow__node[data-id="sparse"] .node-title').click()
  await expect(page.locator('.selection-count')).toHaveText('已选 1 项')
  await page.keyboard.press('l')
  await expect(page.locator('.selection-count')).toHaveText('已选 1 项')
  await page.keyboard.press('t')
  const tasks = page.getByRole('dialog', { name: '评审任务', exact: true })
  await expect(tasks).toBeVisible()
  await page.keyboard.press('f')
  await expect(page.locator('.app-shell')).not.toHaveClass(/is-focused/)
  await page.keyboard.press('Escape')
  await expect(tasks).not.toBeVisible()
})
