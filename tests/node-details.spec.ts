import { expect, test } from '@playwright/test'
import { sampleReview } from '../src/sample.ts'
import { openInspector } from './ui.ts'

const first = sampleReview.nodes.find(node => node.id === 'upgrade-start')!
const second = sampleReview.nodes.find(node => node.id === 'upgrade-toggle')!
const firstNode = '.react-flow__node[data-id="upgrade-start"]'
const secondNode = '.react-flow__node[data-id="upgrade-toggle"]'

test('one review panel keeps selected rules and reveals data and source evidence on demand', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.canvas')).toHaveAttribute('data-viewport-ready', 'true')
  await expect(page.locator('.node-footer')).toHaveCount(0)
  await expect(page.locator('.graph-toolbar').getByRole('button', { name: '步骤详情', exact: true })).toHaveCount(0)
  await page.locator(firstNode).locator('.node-title').click()
  await expect(page.locator('.inspector')).not.toHaveClass(/is-open/)
  const details = await openInspector(page, 'detail')
  await expect(details).toBeVisible()
  await expect(page.locator(firstNode)).toHaveClass(/selected/)
  await expect(details.locator('.panel-title')).toHaveText(first.title)
  await expect(details).toContainText(first.detail)
  await expect(details.getByText('本场景的步骤与连线', { exact: true })).toHaveCount(0)
  await expect(details.locator('.coverage-note')).toHaveCount(0)
  const data = details.locator('.data-details')
  await expect(data).not.toHaveAttribute('open')
  await data.locator('summary').click()
  await expect(data.locator('.state-change')).toContainText(first.input)
  await expect(data.locator('.state-change')).toContainText(first.output)
  const evidence = details.locator('.evidence')
  await evidence.locator('summary').click()
  await expect(evidence).toContainText(first.evidence[0].symbol)
  await expect(evidence).toContainText(`${first.evidence[0].path}:${first.evidence[0].startLine}`)
})

test('the panel opens with Enter and Space and remembers the last content tab', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.canvas')).toHaveAttribute('data-viewport-ready', 'true')
  await page.locator(secondNode).locator('.node-title').click()
  const panelButton = page.locator('.graph-toolbar').getByRole('button', { name: /^评审面板/ })
  await panelButton.focus()
  await panelButton.press('Enter')
  await expect(page.locator('.inspector.is-open')).toBeVisible()
  await page.locator('.inspector-tabs').getByRole('button', { name: '详情', exact: true }).click()
  await expect(page.locator('.inspector.is-open .panel-title')).toHaveText(second.title)
  await expect(page.locator(secondNode)).toHaveClass(/selected/)
  await page.getByRole('button', { name: '收起侧栏', exact: true }).click()
  await panelButton.focus()
  await panelButton.press('Space')
  await expect(page.locator('.inspector.is-open .panel-title')).toHaveText(second.title)
  await expect(panelButton).toHaveAttribute('aria-expanded', 'true')
})

test('switching node tabs preserves the docked editor and its frozen target before returning to the review panel', async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('/')
  await expect(page.locator('.canvas')).toHaveAttribute('data-viewport-ready', 'true')
  await page.locator(firstNode).hover()
  await page.getByRole('button', { name: `批注：${first.title}`, exact: true }).click()
  const editor = page.getByRole('dialog', { name: '流程批注', exact: true })
  const input = editor.getByLabel('问题与预期行为')
  const body = '查看其他步骤时保留这条未完成的意见。'
  await input.fill(body)
  await input.evaluate(element => { element.dataset.editorIdentity = 'original' })
  await openInspector(page, 'detail')
  await expect(editor).toBeVisible()
  await expect(input).toHaveValue(body)
  await expect(editor.locator('.composer-targets')).toHaveText(first.title)
  await expect(page.locator('.inspector-body .panel-title')).toHaveText(first.title)
  await editor.getByRole('button', { name: '移到侧栏编辑', exact: true }).click()
  await expect(editor).toHaveClass(/is-docked/)
  await page.locator(secondNode).locator('.node-title').click()
  for (const tab of ['详情', '代码 diff', '讨论'] as const) {
    await editor.getByRole('tab', { name: tab, exact: true }).click()
    await expect(editor.getByRole('tabpanel', { name: tab, exact: true })).toBeVisible()
    await expect(input).toHaveAttribute('data-editor-identity', 'original')
    await expect(input).toHaveValue(body)
    await expect(editor.locator('.composer-targets')).toHaveText(first.title)
    if (tab === '详情') await expect(editor.getByRole('tabpanel', { name: tab, exact: true })).toContainText(first.detail)
  }
  await editor.getByRole('button', { name: '返回图内编辑', exact: true }).click()
  await openInspector(page, 'detail')
  await page.locator(secondNode).locator('.node-title').click()
  await expect(editor).not.toBeVisible()
  await expect(page.locator('.inspector-body .panel-title')).toHaveText(second.title)
  const drafts = await page.evaluate(() => JSON.parse(localStorage.getItem('logic-margin:drafts')!))
  expect(drafts[0]).toMatchObject({ body, targets: [{ kind: 'node', id: first.id }] })
  await openInspector(page, 'drafts')
  await page.locator('.draft-list').getByRole('button', { name: '继续编辑', exact: true }).click()
  await expect(editor).toBeVisible()
  await expect(input).toHaveValue(body)
  await expect(editor.locator('.composer-targets')).toHaveText(first.title)
  await input.fill(`${body} 继续编辑。`)
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('logic-margin:drafts')!)[0].body)).toBe(`${body} 继续编辑。`)
})
