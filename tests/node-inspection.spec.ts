test('professional diff highlights words, navigates changes, shares scrolling and stays read only', async ({ page }) => {
  const before = Array.from({ length: 90 }, (_, index) => `const item${index} = ${index};`).join('\n')
  const after = before.replace('item10 = 10', 'item10 = 110').replace('item70 = 70', 'item70 = 170')
  await openFixture(page, fixture(before, after))
  await page.getByRole('button', { name: `讨论：${title}`, exact: true }).click()
  const window = surface(page)
  await window.getByRole('tab', { name: '代码 diff', exact: true }).click()
  await expect(window.getByRole('status')).toHaveText('2 处差异')
  await expect(window.locator('.cm-collapsedLines').first()).toBeVisible()
  await expect(window.locator('.tok-keyword').first()).toHaveText('const')
  await expect(window.locator('.cm-changedText').first()).toHaveText('1')
  await window.getByRole('button', { name: '移到侧栏编辑', exact: true }).click()
  await page.getByRole('separator', { name: '调整右侧栏宽度' }).focus()
  await page.keyboard.press('End')
  await window.getByRole('button', { name: '并排', exact: true }).click()
  await window.getByRole('button', { name: '展开全文', exact: true }).click()
  await expect(window.locator('.cm-collapsedLines')).toHaveCount(0)
  const merge = window.locator('.cm-mergeView')
  await merge.evaluate(element => { element.scrollTop = 500 })
  await expect.poll(() => merge.evaluate(element => element.scrollTop)).toBeGreaterThan(400)
  const oldLine = merge.locator('.cm-merge-a .cm-line').filter({ hasText: /^const item35 =/ })
  const newLine = merge.locator('.cm-merge-b .cm-line').filter({ hasText: /^const item35 =/ })
  await expect(oldLine).toBeVisible()
  expect((await oldLine.boundingBox())!.y).toBeCloseTo((await newLine.boundingBox())!.y, 0)
  await window.getByRole('button', { name: '下一处差异', exact: true }).click()
  await expect.poll(() => merge.evaluate(element => element.scrollTop)).toBeLessThan(500)
  await window.getByRole('button', { name: '下一处差异', exact: true }).click()
  await expect.poll(() => merge.evaluate(element => element.scrollTop)).toBeGreaterThan(1000)
  const content = merge.locator('.cm-merge-b .cm-content')
  await expect(content).toHaveAttribute('contenteditable', 'false')
  await expect(content).toHaveAttribute('aria-readonly', 'true')
  await content.focus(); await page.keyboard.type('doNotEdit')
  await expect(content).not.toContainText('doNotEdit')
  await expect(window.locator('.cm-chunkButtons')).toHaveCount(0)
  await page.keyboard.press('Shift+F7')
  await expect.poll(() => merge.evaluate(element => element.scrollTop)).toBeLessThan(500)
  const stored = await page.evaluate(id => JSON.parse(localStorage.getItem(`logic-margin:review:${id}`)!), 'node-inspection-fixture')
  expect(stored.nodes[0].evidence[0].code).toBe(after)
})

